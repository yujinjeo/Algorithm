# dp
# 1. 큰 문제를 작은 문제로 쪼갤 수 있다.
# 2. 작은 문제가 그 다음 문제의 답이 된다는 것이 보장되어 있다.

import sys

input= sys.stdin.readline

n=int(input())
lst=[int(input()) for _ in range(n)]

# n번째까지 고려했을 때 마실 수 있는 최대 양을 저장하는 리스트이다. 
# n번째를 먹었을 때 최대값을 저장하면, 이후 n+1, n+3 값을 찾을 때, n번째를 선택할 경우 꼭 그 음료를 먹는 경우로 계산하게 된다. 
# 왜 n번째를 먹는 걸로 계산하면 안돼? 왜 최대값으로 해야해? 
# 왜냐면 n-3까지만 고려하기 때문에 n-4를 먹을 수도 있는건데 n-3을 반드시 먹는 선택을 해버리면 최적의 해가 안나온다.
# 근데 왜 가장긴증가하는수열은 끝만 고려하는거야? 그건, 인덱스 전체를 둘러보기 때문에 특정 인덱스만 확인하는 게 아니라서, 전체 다 확인해도 괜찮은거지. 
# 그런데 이건, 경우의 수가 있으니까, n까지 고려했을 때를 넣어야 최적의 해를 넣을 수 있는거야.

# 그래서 고려해야 하는 경우는 모두 3가지,
# 1.() x o o
# 2.  () x o
# 3.    () x
# 왜 이렇게 경우의 수로 나누었을까? 먼저 있는 n을 포함하는 경우를 생각한 후에, n을 포함하지 않는 경우를 세면 나온다!#

# 왜 계단오르기같은 문제처럼 경우의 수를 나눠서 풀어야 했지? 
# 왜냐하면 보통, 중간에 한칸을 띄워야 한다 몇 칸마다 띄어야 한다는 조건이 있는 경우는 대부분 경우의수로 문제 해결이야. 

dp=[0 for _ in range(n)]
dp[0]=lst[0]
dp[1]=dp[0]+lst[1]
dp[2]=max(lst[2]+lst[1], lst[2]+lst[0], dp[1])

for i in range(1,n):
  dp[i]=max(dp[i-3]+lst[i-1]+lst[i], dp[i-2]+lst[i], dp[i-1])
  
print(dp[n-1])
